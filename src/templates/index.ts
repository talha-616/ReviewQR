const solid = (
  color: string,
  extras: Partial<BackgroundConfig> = {},
): BackgroundConfig => ({
  kind: "solid",
  color,
  pattern: "none",
  texture: "none",
  customImage: null,
  imageZoom: 1,
  imageX: 50,
  imageY: 50,
  overlay: "#000000",
  overlayOpacity: 0,
  blur: 0,
  brightness: 100,
  ...extras,
});

const gradient = (
  color: string,
  secondaryColor: string,
  angle = 160,
  extras: Partial<BackgroundConfig> = {},
): BackgroundConfig => ({
  kind: "gradient",
  color,
  secondaryColor,
  gradientAngle: angle,
  pattern: extras.pattern ?? "none",
  texture: extras.texture ?? "none",
  customImage: null,
  imageZoom: 1,
  imageX: 50,
  imageY: 50,
  overlay: extras.overlay ?? "#000000",
  overlayOpacity: extras.overlayOpacity ?? 0,
  blur: extras.blur ?? 0,
  brightness: extras.brightness ?? 100,
  ...extras,
});

const typeStyle = (
  font: CardFontId,
  size: number,
  weight: number,
  color: string,
  extras: Partial<TextStyle> = {},
): TextStyle => ({
  font,
  size,
  weight,
  letterSpacing: extras.letterSpacing ?? 0,
  color,
  align: extras.align ?? "center",
  transform: extras.transform ?? "none",
});

