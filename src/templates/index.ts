export function getTemplate(id: string) {
  return templatesById[id] ?? templates[0];
}

export function createDesignFromTemplate(
  template: DesignTemplate,
  previous?: Partial<DesignState>,
): DesignState {
  return {
    templateId: template.id,
    printSize: previous?.printSize ?? "square",
    businessName: previous?.businessName ?? "Your Business",
    message: previous?.message ?? template.config.defaultMessage,
    cta: previous?.cta ?? template.config.defaultCta,
    reviewUrl: previous?.reviewUrl ?? "",
    colors: { ...template.config.colors },
    background: { ...template.config.background },
    layout: {
      showGoogleBadge: true,
      googleBadgePosition: "above-qr",
      googleBadgeStyle: "multicolor",
      ...template.config.layout,
      ...(previous?.layout ?? {}),
    },
    qrStyle: template.config.qrStyle,
    businessNameStyle: { ...template.config.businessName },
    messageStyle: { ...template.config.message },
    ctaStyle: { ...template.config.cta },
    logo: previous?.logo ?? { src: null, size: 12, position: "top" },
  };
}
